// Bundles the stdio servers with esbuild, as services/* do:
// - dist/index.mjs: the full Afterglow server used by .kiro/settings/mcp.json (gitignored build output).
// - powers/night-vision/server/night-vision-mcp.mjs: the Power's luminance-only server, one
//   self-contained file so a project that installs the Power needs only Node, not this repo.
import { build } from 'esbuild';

const shared = {
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  // pngjs is CommonJS and requires Node built-ins at run time; give the ES module a real `require`.
  banner: {
    js: [
      '#!/usr/bin/env node',
      "import { createRequire as __agCreateRequire } from 'node:module';",
      'const require = __agCreateRequire(import.meta.url);',
    ].join('\n'),
  },
};

await build({ ...shared, entryPoints: ['src/index.ts'], outfile: 'dist/index.mjs' });
console.log('built dist/index.mjs');

await build({
  ...shared,
  entryPoints: ['src/power.ts'],
  outfile: '../../powers/night-vision/server/night-vision-mcp.mjs',
  minify: true,
  banner: {
    js: [
      shared.banner.js,
      '// Generated by `pnpm --filter @afterglow/mcp-server build` from tools/mcp-server/src/power.ts.',
      '// Do not edit; rebuild. Apache-2.0. Bundles @modelcontextprotocol/sdk (MIT), zod (MIT), pngjs (MIT).',
    ].join('\n'),
  },
});
console.log('built powers/night-vision/server/night-vision-mcp.mjs');
