/**
 * Formulary types. Pure module: no I/O, no timers, no randomness.
 *
 * The validated formulary is produced by the `afterglow-formulary` review
 * pipeline (AI proposes, a second model family checks, a licensed pharmacist
 * approves, the pipeline signs). This module never contains drug data.
 */

export type Condition = 'unopened' | 'inUse';

/** Where the numbers came from; `excerpt` is the label text shown to the user. */
export interface LabelSource {
  readonly title: string;
  readonly url: string;
  readonly excerpt: string;
}

/** The shape in architecture section 10.3. Every field is part of the signed payload. */
export interface FormularyEntry {
  readonly product: string;
  readonly labelVersion: string;
  readonly condition: Condition;
  /** Highest temperature the label allows during the room-temperature allowance (Celsius). */
  readonly maxTempC: number;
  /** How long the label allows that allowance, in days. */
  readonly maxDays: number;
  readonly notes: string;
  readonly source: LabelSource;
  readonly approver: string;
  /** ISO date (`YYYY-MM-DD`) or UTC timestamp (`YYYY-MM-DDTHH:MM:SSZ`). */
  readonly approvedAt: string;
  readonly signature: string;
}

declare const validatedBrand: unique symbol;

/**
 * An entry that passed `buildFormulary`. The brand stops honest mistakes; the
 * module-private registry in `admit.ts` is what stops a cast (FM-03).
 */
export type ValidatedEntry = FormularyEntry & { readonly [validatedBrand]: true };

/**
 * Injected, synchronous signature check over the canonical payload. The core
 * imports no crypto: the adapter layer owns the trust anchors and verifies
 * (asynchronously) before handing this function to the core. Only an exact
 * `true` counts.
 */
export type Verifier = (payload: string, signature: string) => boolean;

export type RejectionReason = 'malformed' | 'signature' | 'conflict';

export interface Rejection {
  /** Product name when it could be read safely, else null. Never the signature. */
  readonly product: string | null;
  readonly reason: RejectionReason;
  readonly detail: string;
}

export interface Formulary {
  readonly formularyVersion: string;
  readonly entries: readonly ValidatedEntry[];
  readonly rejected: readonly Rejection[];
}

export interface TemperatureSample {
  /** Minutes on the same clock as the window. */
  readonly minute: number;
  readonly tempC: number;
}

/** The window to assess and the temperature history over it. */
export interface ClockInput {
  /** When the medicine first left refrigeration, or when power was lost. */
  readonly startMinute: number;
  readonly nowMinute: number;
  /** Strictly increasing minutes; the first sample must be at or before `startMinute`. */
  readonly samples: readonly TemperatureSample[];
}

/** What the screen must show next to every number (label-only-medicine rule 6). */
export interface ClockProvenance {
  readonly product: string;
  readonly condition: Condition;
  readonly labelVersion: string;
  readonly approver: string;
  readonly approvedAt: string;
  readonly source: LabelSource;
  readonly entryNotes: string;
  readonly disclaimer: string;
}

interface ClockCommon {
  readonly provenance: ClockProvenance;
  /** `maxDays` converted to minutes. */
  readonly budgetMinutes: number;
  /** Always within 0..budgetMinutes. */
  readonly consumedMinutes: number;
  /** True when any temperature in the window reached 0 C or below (FM-12). */
  readonly reachedFreezing: boolean;
  /** Plain-language lines; generated by this module, never label-derived. */
  readonly message: string;
  readonly lines: readonly string[];
}

export type ClockResult =
  | (ClockCommon & {
      readonly kind: 'noExcursion';
      readonly remainingMinutes: number;
    })
  | (ClockCommon & {
      readonly kind: 'consuming';
      readonly remainingMinutes: number;
    })
  | (ClockCommon & {
      readonly kind: 'exhausted';
      readonly remainingMinutes: 0;
      readonly exhaustedAtMinute: number;
    })
  | (ClockCommon & {
      readonly kind: 'beyondLabel';
      readonly sinceMinute: number;
    })
  | {
      readonly kind: 'unknown';
      readonly reason: string;
      readonly whatWouldResolveIt: string;
    };

export type LookupResult =
  | { readonly kind: 'found'; readonly entry: ValidatedEntry }
  | {
      readonly kind: 'notInTable';
      readonly message: string;
      readonly canSubmitLabelForReview: true;
    };
